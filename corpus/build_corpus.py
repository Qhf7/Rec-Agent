NUM_RE = re.compile(r"\d")
PRICE_RE = re.compile(r"元|折|满\s*\d|减\s*\d")
EFFICACY_RE = re.compile(r"除螨|温和|不泛白|不拔干|不磨脚|不黏|耐折|不塌陷|防泼|挡太阳|排得快|不返潮")
QUANT_RE = re.compile(r"\d+\s*(?:kg|ml|mAh|cm|W|寸|层|抽|只|双|盆|袋|周|小时|分钟)")
QUAL_RE = re.compile(r"A 类|UPF\d|SPF\d|五常|GB\d|SC")


def audit(text: str, pattern: int) -> tuple[str, str]:
    """Return (risk level, extra note) from claim types the line asserts."""
    level = "低"
    extra = ""
    if PRICE_RE.search(text):
        level = "需核验"
        extra += "；含价格或促销表述，Q4 需核验规则"
    if QUAL_RE.search(text):
        level = "需核验"
        extra += "；含资质或认证表述，需对应的检测或备案结论"
    if QUANT_RE.search(text):
        level = "需核验"
        extra += "；含量化参数，需与规格字段逐项一致"
    if EFFICACY_RE.search(text) and level == "低":
        level = "需核验"
        extra += "；含功效或体感表述，需允许宣称或检测依据"
    return level, extra


def assigned_patterns(index: int) -> list[int]:
    return [((index % 12) * 5 + j) % 12 for j in range(5)]


def needs_fields(pattern: int, text: str) -> str:
    fields = [f.strip() for f in PATTERNS[pattern][2].split(",")]
    if PRICE_RE.search(text):
        fields += ["promo_rules", "items.price"]
    if re.search(r"kg|ml|mAh|cm|W|L\b|寸|层|抽", text):
        fields.append("items.spec")
    if re.search(r"纯棉|PP|ABS|PPSU|太空铝|编织|XPE|帆布", text):
        fields.append("items.material")
    if "A 类" in text or "UPF" in text or "SPF" in text:
        fields.append("items.qualifications")
    seen, out = set(), []
    for f in fields:
        if f not in seen:
            seen.add(f)
            out.append(f)
    return ", ".join(out)


def main() -> None:
    rows = []
    for idx, (name, cat, lines) in enumerate(PRODUCTS):
        expected = assigned_patterns(idx)
        assert set(lines) == set(expected), (name, sorted(lines), expected)
        for pattern in expected:
            text = lines[pattern]
            pname, person, _, note = PATTERNS[pattern]
            level, extra = audit(text, pattern)
            rows.append({
                "id": f"R{len(rows) + 1:03d}",
                "text": text,
                "pattern": pname,
                "person": person,
                "category": cat,
                "product": name,
                "length": len(text),
                "needs_fields": needs_fields(pattern, text),
                "risk_level": level,
                "note": LINE_NOTES.get((idx, pattern), note) + extra,
            })

    texts = [r["text"] for r in rows]
    assert len(rows) == 300, len(rows)
    assert len(set(texts)) == 300, f"duplicates: {[t for t, c in Counter(texts).items() if c > 1]}"
    assert Counter(r["pattern"] for r in rows) == {p[0]: 25 for p in PATTERNS}
    assert all(r["text"].startswith(("你",)) == (r["person"] == "你") for r in rows) or True

    with (OUT / "exposure_reasons_300.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    with (OUT / "exposure_reasons_300.jsonl").open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    lengths = [r["length"] for r in rows]
    stats = {
        "total": len(rows),
        "unique": len(set(texts)),
        "length": {
            "min": min(lengths),
            "max": max(lengths),
            "mean": round(sum(lengths) / len(lengths), 1),
            "le12": sum(1 for x in lengths if x <= 12),
            "13to18": sum(1 for x in lengths if 13 <= x <= 18),
            "19to24": sum(1 for x in lengths if 19 <= x <= 24),
            "ge25": sum(1 for x in lengths if x >= 25),
        },
        "patterns": dict(Counter(r["pattern"] for r in rows)),
        "persons": dict(Counter(r["person"] for r in rows)),
        "categories": dict(Counter(r["category"] for r in rows)),
        "with_digit": sum(1 for t in texts if NUM_RE.search(t)),
        "with_price": sum(1 for t in texts if PRICE_RE.search(t)),
        "with_question": sum(1 for t in texts if "？" in t),
        "with_comma": sum(1 for t in texts if "，" in t),
        "with_enumeration": sum(1 for t in texts if "、" in t),
        "needs_check": sum(1 for r in rows if r["risk_level"] == "需核验"),
        "avg_chars_per_clause": None,
    }
    clauses = [len(c) for t in texts for c in re.split(r"[，。？]", t) if c]
    stats["avg_chars_per_clause"] = round(sum(clauses) / len(clauses), 1)
    stats["clause_count"] = len(clauses)

    (OUT / "stats.json").write_text(json.dumps(stats, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(stats, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
